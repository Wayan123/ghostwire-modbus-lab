#!/usr/bin/env python3
"""Run one Kiro CLI (V3, headless) task and record verifiable evidence.

omp, a shell, or a human calls this; Kiro does the work. Every run appends a
summary to docs/kiro-log/LEDGER.md and keeps the raw stream-json transcript in
docs/kiro-log/runs/ so the Kiro usage claimed in the Devpost write-up can be
traced to real sessions.

Usage:
  tools/kiro_bridge.py --agent ghostwire-builder "Implement task 3 of spec phantom-writer"
  tools/kiro_bridge.py --prompt-file prompt.md --agent ot-security-reviewer
  tools/kiro_bridge.py --resume-id sess_... "continue"

Stdlib only. Exit code mirrors kiro-cli.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOG_DIR = ROOT / "docs" / "kiro-log"
RUNS = LOG_DIR / "runs"
LEDGER = LOG_DIR / "LEDGER.md"
SECRET = re.compile(r"(?i)(api[_-]?key|token|secret|password|authorization)[\"':= ]+[^\s\"',}]{8,}")


def redact(text: str) -> str:
    return SECRET.sub(lambda m: m.group(1) + "=<redacted>", text)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("prompt", nargs="?")
    ap.add_argument("--prompt-file")
    ap.add_argument("--agent")
    ap.add_argument("--model")
    ap.add_argument("--resume-id")
    ap.add_argument("--trust", default="all", help="'all' or comma-separated V3 tool IDs")
    ap.add_argument("--timeout", type=int, default=3600)
    ap.add_argument("--label", default="", help="short label for the ledger")
    a = ap.parse_args()

    prompt = pathlib.Path(a.prompt_file).read_text(encoding="utf-8") if a.prompt_file else a.prompt
    if not prompt or not prompt.strip():
        ap.error("prompt or --prompt-file required")

    cmd = ["kiro-cli", "chat", "--v3", "--no-interactive", "--trust-workspace", "--output-format", "stream-json"]
    cmd += ["--trust-all-tools"] if a.trust == "all" else [f"--trust-tools={a.trust}"]
    if a.agent:
        cmd += ["--agent", a.agent]
    if a.model:
        cmd += ["--model", a.model]
    if a.resume_id:
        cmd += ["--resume-id", a.resume_id]
    cmd.append(prompt)

    RUNS.mkdir(parents=True, exist_ok=True)
    stamp = dt.datetime.now().astimezone()
    run_name = f"{stamp:%Y%m%dT%H%M%S}-{a.agent or 'default'}"
    raw_path = RUNS / f"{run_name}.jsonl"

    session = status = final = ""
    tools: list[str] = []
    files: set[str] = set()
    credits = 0.0
    with raw_path.open("w", encoding="utf-8") as raw:
        proc = subprocess.Popen(cmd, cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, encoding="utf-8")
        try:
            assert proc.stdout
            for line in proc.stdout:
                raw.write(redact(line))
                try:
                    ev = json.loads(line)
                except json.JSONDecodeError:
                    continue
                data = ev.get("data", {})
                if ev.get("type") == "runFinished":
                    session = data.get("sessionId", session)
                    status = data.get("status", "")
                    final = data.get("finalText", "")
                    continue
                up = data.get("update", {})
                session = data.get("sessionId", session)
                kind = up.get("sessionUpdate")
                if kind == "agent_message_chunk":
                    print(up.get("content", {}).get("text", ""), end="", flush=True)
                elif kind == "tool_call":
                    tools.append(up.get("title", "?"))
                    for loc in up.get("locations") or []:
                        p = loc.get("path", "")
                        if up.get("kind") in ("edit", "delete", "write") and p:
                            files.add(p)
                elif kind == "session_info_update":
                    for c in up.get("_meta", {}).get("kiro", {}).get("credits", []) or []:
                        credits = max(credits, float(c.get("usage", 0)))
            proc.wait(timeout=a.timeout)
        except subprocess.TimeoutExpired:
            proc.kill()
            status = "timeout"
        err = proc.stderr.read() if proc.stderr else ""
    print()

    rel = lambda p: str(pathlib.Path(p)).replace(str(ROOT) + "/", "")
    counts: dict[str, int] = {}
    for t in tools:
        counts[t] = counts.get(t, 0) + 1
    if not LEDGER.exists():
        LEDGER.write_text("# Kiro run ledger\n\nGenerated by `tools/kiro_bridge.py`. Each entry is one headless Kiro CLI V3 session; raw transcripts are in `runs/`.\n\n", encoding="utf-8")
    with LEDGER.open("a", encoding="utf-8") as led:
        led.write(f"## {stamp:%Y-%m-%d %H:%M %Z} · {a.label or (a.agent or 'default')}\n\n")
        led.write(f"- Agent: `{a.agent or 'kiro_default'}` · model: `{a.model or 'agent/default'}` · status: **{status or proc.returncode}** · credits: {credits:.2f}\n")
        led.write(f"- Session: `{session}` · transcript: `runs/{raw_path.name}`\n")
        led.write(f"- Prompt: {redact(prompt.strip().splitlines()[0])[:300]}\n")
        if counts:
            led.write("- Tools: " + ", ".join(f"{k}×{v}" for k, v in sorted(counts.items())) + "\n")
        if files:
            led.write("- Files changed: " + ", ".join(f"`{rel(f)}`" for f in sorted(files)) + "\n")
        led.write(f"- Result: {redact(final.strip())[:600].replace(chr(10), ' ')}\n\n")
    if err.strip() and proc.returncode:
        print(redact(err[-2000:]), file=sys.stderr)
    return proc.returncode or (1 if status not in ("success", "") else 0)


if __name__ == "__main__":
    sys.exit(main())
